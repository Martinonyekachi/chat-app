import 'dotenv/config'
import pg from 'pg'

if (!process.env.DATABASE_URL) {
  throw new Error('DATABASE_URL must be set.')
}

const databaseUrl = new URL(process.env.DATABASE_URL)
if (process.env.NODE_ENV === 'production') {
  databaseUrl.searchParams.set('sslmode', 'verify-full')
}

export const pool = new pg.Pool({
  connectionString: databaseUrl.toString(),
  max: 10,
  idleTimeoutMillis: 30_000,
  connectionTimeoutMillis: 5_000,
})

pool.on('error', (error) => {
  console.error('Unexpected PostgreSQL pool error:', error.message)
})

export async function initializeDatabase() {
  const client = await pool.connect()

  try {
    await client.query('BEGIN')
    await client.query(`
      CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username VARCHAR(80),
        email VARCHAR(254) NOT NULL,
        password_hash TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `)
    await client.query('ALTER TABLE users ADD COLUMN IF NOT EXISTS username VARCHAR(80)')
    await client.query(`
      DO $$
      BEGIN
        IF EXISTS (
          SELECT 1 FROM information_schema.columns
          WHERE table_schema = 'public'
            AND table_name = 'users'
            AND column_name = 'display_name'
        ) THEN
          EXECUTE 'UPDATE users SET username = display_name WHERE username IS NULL';
          EXECUTE 'ALTER TABLE users ALTER COLUMN display_name DROP NOT NULL';
        END IF;
      END
      ;
      $$
    `)
    await client.query(`
      UPDATE users
      SET username = split_part(email, '@', 1)
      WHERE username IS NULL OR btrim(username) = ''
    `)
    await client.query('ALTER TABLE users ALTER COLUMN username SET NOT NULL')
    await client.query(`
      CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique
      ON users (LOWER(email))
    `)
    await client.query(`
      CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_unique
      ON users (LOWER(username))
    `)
    await client.query(`
      CREATE TABLE IF NOT EXISTS auth_sessions (
        token_id UUID PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        expires_at TIMESTAMPTZ NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `)
    await client.query(`
      CREATE INDEX IF NOT EXISTS auth_sessions_expiry_idx
      ON auth_sessions (expires_at)
    `)
    await client.query(`
      CREATE TABLE IF NOT EXISTS conversations (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_one_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        user_two_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        CONSTRAINT conversations_distinct_users CHECK (user_one_id < user_two_id),
        CONSTRAINT conversations_unique_pair UNIQUE (user_one_id, user_two_id)
      )
    `)
    await client.query(`
      CREATE TABLE IF NOT EXISTS messages (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
        sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        content TEXT NOT NULL CHECK (
          char_length(btrim(content)) > 0 AND char_length(content) <= 4000
        ),
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `)
    await client.query(`
      CREATE INDEX IF NOT EXISTS messages_conversation_created_idx
      ON messages (conversation_id, created_at, id)
    `)
    await client.query(`
      CREATE INDEX IF NOT EXISTS conversations_user_two_idx
      ON conversations (user_two_id)
    `)
    await client.query('COMMIT')
  } catch (error) {
    await client.query('ROLLBACK')
    throw error
  } finally {
    client.release()
  }
}
